/** Перемешивание Фишера — Йетса (не мутирует исходный массив). */
function shuffleArray(source) {
    const arr = source.slice();
    for (let i = arr.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
}

/** Возвращает копию вопроса со случайно перемешанными вариантами ответов. */
function shuffleAnswers(question) {
    const letters = ["A", "B", "C", "D"];
    const correctText = question.answers[question.correct];
    const texts = shuffleArray(letters.map((letter) => question.answers[letter]));

    const answers = {};
    let correct = "A";
    letters.forEach((letter, index) => {
        answers[letter] = texts[index];
        if (texts[index] === correctText) {
            correct = letter;
        }
    });

    return { question: question.question, answers, correct };
}

/**
 * Собирает набор из 15 вопросов для новой партии:
 * по `perTier` случайных вопросов из каждого уровня сложности,
 * в порядке от простых к сложным, с перемешанными вариантами ответов.
 */
function buildQuestionSet(perTier = 5) {
    const set = [];
    ["easy", "medium", "hard"].forEach((tier) => {
        shuffleArray(QUESTION_BANK[tier])
            .slice(0, perTier)
            .forEach((question) => set.push(shuffleAnswers(question)));
    });
    return set;
}

